/// Pre-selected filter combinations surfaced in the UI. A preset only
/// sets trip parameters — the rule matrix still decides every item, so
/// overriding season/weather afterwards re-filters the list correctly.
class PackingPreset {
  final String id;
  final String name;
  final String description;
  final TripActivity activity;
  final CarryMode carry;
  final AccommodationType accommodation;
  final TripSeason season;

  const PackingPreset({
    required this.id,
    required this.name,
    required this.description,
    required this.activity,
    required this.carry,
    required this.accommodation,
    required this.season,
  });

  void apply(Trip trip) {
    trip.activity = activity;
    trip.carry = carry;
    trip.accommodation = accommodation;
    trip.season = season;
  }
}

